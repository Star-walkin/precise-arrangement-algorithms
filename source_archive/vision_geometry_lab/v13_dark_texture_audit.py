def run(output):
    from .v13_dark_texture_features import analyze_patch, PARAMETERS
    output=Path(output).resolve()
    if output.exists():
        raise FileExistsError('Do not overwrite a previous diagnostic')
    manifest=read(MANIFEST);samples=selected_train_samples(manifest)
    source=Path(__file__).resolve()
    feature_source=source.with_name('v13_dark_texture_features.py')
    cached_path=source.parent/'outputs/v12_training_profile_audit/records.json'
    cached=read(cached_path)
    widths={r['sample_id']:r['independent_width']['width_px'] for r in cached}
    for sample in samples:
        row=next(r for r in cached if r['sample_id']==sample['sample_id'])
        for key in ('image_sha256','annotation_sha256','quality_sha256'):
            if row[key]!=sample[key]:raise ValueError('Width cache source mismatch')
    # Freeze selected snapshots BEFORE opening RGB or measuring scores.
    output.mkdir(parents=True);(output/'patches').mkdir()
    protocol=dict(question='Do dark termination and tangent periodicity distinguish labeled boundaries from within-rope cuts?',
        input_is_gt_conditioned=True,detector_accuracy=False,hardware_access=False,force_command=None,
        source_snapshot={str(p):sha(p) for p in (source,feature_source)},manifest_sha256=sha(MANIFEST),
        artifact_snapshot={str(cached_path):sha(cached_path)},
        selected_train_ids=[s['sample_id'] for s in samples],parameters=PARAMETERS,
        snapshot={s['sample_id']:{k:s[k] for k in ('image_sha256','annotation_sha256','quality_sha256')} for s in samples},
        patch=dict(rows=ROWS,cols=COLS,half_length_local_labeled_widths=HALF_LENGTH_WIDTHS,
            half_normal_local_labeled_widths=HALF_NORMAL_WIDTHS,alpha_cuts=list(ALPHAS),
            geometry='curvilinear trusted center arc; each row uses actual two annotated edge intersections',
            spacing='max(12px, .5 independent free width)',equal_support='all five cuts share admissibility'),
        main_comparison='surface-side edge alpha1 vs same rope interior .25/.5/.75; flange edge separate',
        metric='paired rank wins (tie half), equal-image macro; no fitted classifier or tuned threshold',
        excluded='outside trusted geometry/image; ambiguous intersection; annotated unknown; all retained as unavailable',
        scope='10 training images, no heldout or 0925 data',selected_visual_ids=list(FIXED_IMAGES),
        optical_period_is_instance_identity=False,unknown_is_not_negative=True)
    write(output/'protocol.json',protocol)
    records=[]
    for sample in samples:
        label=validate_annotation(read(sample['annotation_path']),sample)
        if sha(sample['annotation_path'])!=sample['annotation_sha256']:
            raise ValueError('Changed annotation')
        quality=load_label_quality(sample)
        if quality['quality_sha256']!=sample['quality_sha256']:
            raise ValueError('Changed trusted quality')
        curves=dict(label['polylines']);curves.update(quality.get('supervision_polylines') or {})
        if sample['sample_id'].startswith(('C07__','C08__')) and len(curves['centerline'])!=7:
            raise ValueError('C7-only trusted geometry required')
        gray=cv2.cvtColor(np.asarray(read_clean_image(sample)),cv2.COLOR_RGB2GRAY)
        unknown=np.zeros(gray.shape,np.uint8)
        for poly in label['ignore_polygons']+quality['precision_exclude_polygons']:
            cv2.fillPoly(unknown,[np.rint(poly).astype(np.int32)],255)
        points,positions=arc_geometry(curves['centerline'])
        width=widths[sample['sample_id']]
        if width is None:
            raise ValueError('Known baseline free width unavailable')
        seed=np.asarray(label['polylines']['free_seed'],float)
        direction=seed[-1]-seed[0];direction/=np.linalg.norm(direction)
        for index,distance in enumerate(np.arange(0.,positions[-1]+1e-6,max(12.,width*.5))):
            center=arc_point(points,positions,distance)
            if (center-seed[-1])@direction<0:
                continue
            row=dict(sample_id=sample['sample_id'],group_id=sample['group_id'],section_index=index,
                arc_distance_px=float(distance),arc_fraction=float(distance/positions[-1]))
            data,reason=patches_at(gray,unknown,curves,points,positions,float(distance),width)
            if reason:
                records.append(dict(row,available=False,reason=reason));continue
            candidates=[]
            for alpha,patch in zip(ALPHAS,data.pop('patches')):
                result=analyze_patch(patch,data['normal_step_px'],data['tangent_step_px'])
                name=f'{sample["sample_id"]}__{index:04d}__{alpha:.2f}.png'
                Image.fromarray(patch).save(output/'patches'/name)
                candidates.append(dict(alpha=alpha,features=result,metrics=metrics(result),patch_file=name))
            records.append(dict(row,available=True,geometry=data,candidates=candidates))
        print(sample['sample_id'],sum(r.get('available',False) for r in records if r['sample_id']==sample['sample_id']),flush=True)
    summary=dict(protocol_sha256=sha(output/'protocol.json'),images=10,groups=len({s['group_id'] for s in samples}),
        total_downstream_sections=len(records),matched_available_sections=sum(r.get('available',False) for r in records),
        exclusion_counts=dict(Counter(r['reason'] for r in records if not r.get('available'))),
        comparisons=paired_summary(records),feature_is_boundary_confirmation=False,force_command=None)
    for path,digest in protocol['source_snapshot'].items():
        if sha(path)!=digest:raise ValueError('Source changed during frozen audit')
    for path,digest in protocol['artifact_snapshot'].items():
        if sha(path)!=digest:raise ValueError('Artifact changed during frozen audit')
    for sample in samples:
        if sha(sample['image_path'])!=sample['image_sha256'] or sha(sample['annotation_path'])!=sample['annotation_sha256']:
            raise ValueError('Input changed during audit')
        if load_label_quality(sample)['quality_sha256']!=sample['quality_sha256']:
            raise ValueError('Quality changed during audit')
    write(output/'records.json',records);write(output/'summary.json',summary)
    figures(samples,records,output)
    print(json.dumps(summary,ensure_ascii=False),flush=True)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=BASE)
    run(parser.parse_args().output)
