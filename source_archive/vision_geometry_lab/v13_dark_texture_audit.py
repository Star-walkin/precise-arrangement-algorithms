def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8-sig'))


def write(path, value):
    with Path(path).open('x', encoding='utf-8') as stream:
        json.dump(value, stream, ensure_ascii=False, indent=2, allow_nan=False)


def geometry_at(curves, points, positions, distance, tangent_radius):
    if distance < 0 or distance > positions[-1]:
        return None, 'unannotated_center_extension'
    center = arc_point(points, positions, distance)
    tangent = arc_point(points, positions, min(positions[-1], distance+tangent_radius)) - arc_point(
        points, positions, max(0., distance-tangent_radius))
    norm = np.linalg.norm(tangent)
    if norm <= 1e-8:
        return None, 'degenerate_tangent'
    tangent /= norm
    edges=[]
    for key in ('edge_flange','edge_surface'):
        intersections, reason = normal_intersections(curves[key], center, tangent)
        if reason:
            return None, key+':'+reason
        edges.append(intersections[0]['xy'])
    delta=edges[1]-edges[0]
    width=float(np.linalg.norm(delta))
    if width < 3:
        return None, 'insufficient_labeled_width'
    fraction=float((center-edges[0])@delta/width**2)
    if not 0 <= fraction <= 1:
        return None, 'center_not_between_edges'
    return dict(center=center,tangent=tangent,flange=edges[0],surface=edges[1],width=width), None


def patches_at(gray, unknown, curves, points, positions, distance, free_width):
    """Identical GT-following normalization for true edges and interior cuts.

    No synthetic reflected pixels, no unannotated path extrapolation. Missing
    support invalidates the entire matched set, so contrasts use equal support.
    """
    local, reason=geometry_at(curves,points,positions,distance,free_width*.5)
    if reason:
        return None, reason
    width=local['width']
    distances=distance+np.linspace(-HALF_LENGTH_WIDTHS*width,HALF_LENGTH_WIDTHS*width,ROWS)
    if distances[0] < 0 or distances[-1] > positions[-1]:
        return None,'patch_would_extend_beyond_trusted_center'
    flanges, deltas=[],[]
    for position in distances:
        geo, reason=geometry_at(curves,points,positions,float(position),free_width*.5)
        if reason:
            return None,'patch_geometry:'+reason
        flanges.append(geo['flange']);deltas.append(geo['surface']-geo['flange'])
    flanges,deltas=np.asarray(flanges),np.asarray(deltas)
    offsets=np.linspace(-HALF_NORMAL_WIDTHS,HALF_NORMAL_WIDTHS,COLS)
    patches=[]
    for alpha in ALPHAS:
        xy=flanges[:,None,:]+(alpha+offsets)[None,:,None]*deltas[:,None,:]
        if (np.any(xy[...,0]<0) or np.any(xy[...,0]>=gray.shape[1]-1) or
                np.any(xy[...,1]<0) or np.any(xy[...,1]>=gray.shape[0]-1)):
            return None,'patch_source_image_support_missing'
        xm,ym=xy[...,0].astype(np.float32),xy[...,1].astype(np.float32)
        if np.any(cv2.remap(unknown,xm,ym,cv2.INTER_LINEAR)>0):
            return None,'patch_intersects_annotated_unknown'
        patches.append(cv2.remap(gray,xm,ym,cv2.INTER_LINEAR))
    return dict(patches=patches,center_xy=local['center'].tolist(),labeled_width_px=width,
        normal_step_px=width*2*HALF_NORMAL_WIDTHS/(COLS-1),
        tangent_step_px=width*2*HALF_LENGTH_WIDTHS/(ROWS-1),
        local_width_minmax=[float(np.linalg.norm(deltas,axis=1).min()),float(np.linalg.norm(deltas,axis=1).max())]),None


def metrics(feature):
    transition=feature['transition']
    texture=feature['tangent_texture']
    cross=feature['cross_boundary_texture']
    periodic=all(texture[side]['available'] for side in ('left','right'))
    return dict(abs_center_gradient=transition['absolute_gradient'],
        abs_sided_step=transition['absolute_side_intensity_change'],
        relative_gradient_p90=transition['relative_to_patch_p90'],
        both_sides_periodic_peak_min=min(texture[s]['peak_correlation'] for s in ('left','right')) if periodic else None,
        zero_lag_discontinuity=1-cross['zero_lag_correlation'] if cross['available'] else None,
        shift_aligned_discontinuity=1-cross['maximum_shifted_correlation'] if cross['available'] else None)


def paired_summary(records):
    names=sorted({key for r in records for c in r.get('candidates',[]) for key in c['metrics']})
    summaries=[]
    for key in names:
        groups={}
        missing=0
        for row in records:
            if not row.get('available'):
                continue
            by_alpha={c['alpha']:c for c in row['candidates']}
            positive=by_alpha[1.]['metrics'][key]
            for alpha in (.25,.5,.75):
                negative=by_alpha[alpha]['metrics'][key]
                if positive is None or negative is None:
                    missing+=1;continue
                groups.setdefault(row['sample_id'],[]).append((positive,negative))
        differences=[a-b for pairs in groups.values() for a,b in pairs]
        def win(pairs):
            return float(np.mean([1. if a>b+1e-9 else .5 if abs(a-b)<=1e-9 else 0. for a,b in pairs]))
        image_rates={name:win(pairs) for name,pairs in groups.items()}
        summaries.append(dict(metric=key,paired_comparisons=len(differences),missing_feature_pairs=missing,
            positive_gt_surface_edge=True,negative_gt_within_body_cuts=True,
            greater_is_hypothesis_direction=True,
            pooled_win_fraction=win([p for pairs in groups.values() for p in pairs]) if differences else None,
            macro_image_win_fraction=float(np.mean(list(image_rates.values()))) if image_rates else None,
            median_positive_minus_internal=float(np.median(differences)) if differences else None,
            per_image_win_fraction=image_rates,independent_observations=False))
    return summaries


